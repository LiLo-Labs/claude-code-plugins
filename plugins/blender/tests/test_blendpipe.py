def test_addon_is_importable_shape():
    print("\naddon")
    src = open(os.path.join(ROOT, "blendpipe", "addon.py")).read()
    check("declares bl_info", "bl_info = {" in src)
    check("registers a main-thread pump", "bpy.app.timers.register(_pump" in src)
    check("every handler name is routed",
          all(("\"%s\":" % n) in src for n in
              ("ping", "execute", "scene_summary", "object_info", "import_mesh",
               "export_mesh", "render", "save")))
    # The whole thread-safety argument rests on bpy never being touched from the
    # socket threads, so assert the server class body stays clean of it.
    server = src.split("class BridgeServer:")[1].split("# ---")[0]
    offenders = [l.strip() for l in server.splitlines()
                 if "bpy." in l and "bpy.app.timers" not in l]
    check("BridgeServer never touches bpy off the main thread", not offenders, str(offenders))

    # An invisible panel is not a feature. The sidebar is closed by default and
    # only toggles on N over a 3D viewport, so the Agent panel shipped populated
    # and unseen.
    check("starting the bridge opens the sidebar",
          "_open_sidebar()" in src.split("class BLENDPIPE_OT_start")[1].split("class ")[0])
    check("there is an activity handler for the panel to draw", '"activity": _h_activity' in src)
    check("and it asks Blender to repaint",
          "tag_redraw" in src.split("def _h_activity")[1].split("\ndef ")[0])

    # _h_render restores the caller's engine in a finally, so reading
    # scene.render.engine for the return value names the engine that did not
    # make the pixels -- CYCLES reported for an EEVEE critique render.
    render = src.split("def _h_render(")[1].split("\ndef ")[0]
    before_try = render.split("    try:")[0]
    check("render reports the engine it actually used",
          '"engine": engine_used' in render.split("finally:")[-1]
          and "engine_used = scene.render.engine" in before_try)



def hook(script, event, env=None):
    proc = subprocess.run(
        [sys.executable, os.path.join(ROOT, "hooks", script)],
        input=json.dumps(event), capture_output=True, text=True, timeout=30,
        env={**os.environ, **(env or {})})
    return proc.returncode, proc.stderr


def test_headless_agent():
    """The unattended runner. Its two load-bearing settings are easy to lose.

    Pinning the model is not a preference: the headless default is Sonnet, and
    both sibling plugins document it hallucinating about renders it was shown.
    And without Read in the allowed tools, render_views hands back paths the
    model cannot open -- the critique loop becomes a model describing an image
    it has never seen, which is the exact failure the loop exists to prevent.
    """
    print("\nheadless agent")
    from blendpipe import agent

    check("pins a model rather than taking the headless default",
          agent.MODEL.startswith("claude-opus"), agent.MODEL)
    check("allows Read, so renders can actually be opened", "Read" in agent.TOOLS)
    check("allows execute_python", "mcp__blender__execute_python" in agent.TOOLS)
    check("allows render_views and verify_geometry",
          {"mcp__blender__render_views", "mcp__blender__verify_geometry"} <= set(agent.TOOLS))

    with tempfile.TemporaryDirectory() as tmp:
        path = agent.mcp_config(os.path.join(tmp, "mcp.json"))
        config = json.load(open(path))
        server = config["mcpServers"]["blender"]
        check("writes an MCP config naming one server", list(config["mcpServers"]) == ["blender"])
        check("pointing at this plugin's server",
              server["args"][0].endswith("mcp_blender.py"), server["args"])
        check("with an interpreter that exists", os.path.exists(server["command"]))

    # The guidance is the whole feature on this design, so assert it states the
    # measurable targets rather than naming operators to call.
    guidance = agent.GUIDANCE
    check("guidance names the UV targets",
          all(t in guidance for t in ("overlap", "texel density", "area_sum")))
    check("guidance insists the render is opened", "Read" in guidance)
    check("guidance keeps usable and right apart",
          "USABLE" in guidance and "RIGHT" in guidance)
    check("guidance does not prescribe an unwrap operator",
          "smart_project" not in guidance.lower().replace(" ", "_"))

    # Preflight. An unattended agent pointed at a Blender that is not running
    # does not stop: it errors, reasons, retries, and burns every turn it was
    # given. Nine minutes of exactly that is why this check exists.
    listening = agent.blender_listening
    try:
        agent.blender_listening = lambda **_kw: False
        try:
            agent.run("anything")
            refused = ""
        except RuntimeError as exc:
            refused = str(exc)
    finally:
        agent.blender_listening = listening
    check("refuses to start when Blender is not listening", "not reachable" in refused, refused[:70])
    check("and names the address it tried", "9876" in refused, refused[:70])

    # Connect-only, not a ping: the addon accepts on a background thread and
    # answers on Blender's main thread, so a busy Blender still accepts. A ping
    # round-trip would read "rendering" as "gone" and kill a healthy run.
    source = pathlib.Path(agent.__file__).read_text()
    watch = source.split("class _Watchdog")[1].split("def run(")[0]
    check("the watchdog tests the socket, not a round-trip",
          "create_connection" in source and "ping" not in watch.lower())
    check("and tolerates a miss before killing", "tolerate" in watch)

    missing = agent.shutil.which
    try:
        agent.shutil.which = lambda _name: None
        try:
            agent.run("anything")
            failed = ""
        except RuntimeError as exc:
            failed = str(exc)
    finally:
        agent.shutil.which = missing
    check("says what to do when the claude CLI is absent",
          "claude" in failed and "PATH" in failed and "subscription" in failed,
          failed[:80])


def test_hooks_match_the_names_claude_code_sends():
    """The guardrails were inert in every real install.

    Claude Code namespaces a plugin's MCP tools as
    mcp__plugin_<plugin>_<server>__<tool>; a user-configured server is just
    mcp__<server>__<tool>. The hooks matched only the second form, so neither
    the spend ceiling nor verify-before-export ever fired -- while every check
    below this one passed, because they fed the hooks the name the hooks
    expected. Tests that supply the input under test cannot catch that; these
    assert against both namespaces and against hooks.json itself.
    """
    print("\nhook tool naming")
    sys.path.insert(0, os.path.join(ROOT, "hooks"))
    import hook_state

    plugin_form = "mcp__plugin_blender_blender__%s"
    plain_form = "mcp__blender__%s"
    for suffix in ("export_mesh", "verify_geometry", "generate_mesh"):
        check("is_tool accepts the plugin namespace for %s" % suffix,
              hook_state.is_tool(plugin_form % suffix, suffix))
        check("is_tool accepts a bare server for %s" % suffix,
              hook_state.is_tool(plain_form % suffix, suffix))
    check("is_tool ignores another plugin's tool of the same name",
          not hook_state.is_tool("mcp__plugin_gameassets_gameassets__export_mesh", "export_mesh"))
    check("is_tool ignores a non-MCP tool", not hook_state.is_tool("Bash", "export_mesh"))

    config = json.load(open(os.path.join(ROOT, "hooks", "hooks.json")))
    matchers = {entry["matcher"].rsplit("__", 1)[-1].rstrip("$"): entry["matcher"]
                for event in config["hooks"].values() for entry in event}
    for suffix in ("export_mesh", "verify_geometry", "generate_mesh"):
        pattern = matchers.get(suffix, "")
        check("hooks.json matches the plugin namespace for %s" % suffix,
              bool(re.match(pattern, plugin_form % suffix)), pattern)
        check("hooks.json still matches a bare server for %s" % suffix,
              bool(re.match(pattern, plain_form % suffix)), pattern)

    # The guards must actually run, not just agree in the abstract.
    code, err = hook("guard_export.py",
                     {"session_id": "ns1", "tool_name": plugin_form % "export_mesh",
                      "hook_event_name": "PreToolUse", "tool_input": {"path": "/tmp/x.glb"}})
    check("an unverified export is blocked under the plugin namespace", code == 2, err[:80])


def test_export_guard():
    print("\nexport guard")
    import tempfile
    runs = tempfile.mkdtemp()
    env = {"BLENDPIPE_RUNS": runs}
    export = {"session_id": "t1", "tool_name": "mcp__blender__export_mesh",
              "tool_input": {"path": "/tmp/x.glb"}}

    code, err = hook("guard_export.py", export, env)
    check("export blocked with no verify", code == 2)
    check("and says to run verify_geometry", "verify_geometry" in err)

    def verified(text):
        return {"session_id": "t1", "hook_event_name": "PostToolUse",
                "tool_name": "mcp__blender__verify_geometry", "tool_response": text}

    hook("guard_export.py", verified("VERDICT: FAIL - 2 blocking"), env)
    code, err = hook("guard_export.py", export, env)
    check("export blocked after a failing verify", code == 2)
    check("and refuses to export around the budget", "do not export around it" in err)

    hook("guard_export.py", verified("VERDICT: PASS - 0 blocking"), env)
    code, _ = hook("guard_export.py", export, env)
    check("export allowed after a passing verify", code == 0)

    code, err = hook("guard_export.py", export, dict(env, BLENDPIPE_VERIFY_MAX_AGE="0"))
    check("a stale verify does not count", code == 2 and "Re-run verify_geometry" in err)

    code, _ = hook("guard_export.py",
                   {"session_id": "t1", "tool_name": "mcp__blender__execute_python",
                    "tool_input": {"code": "print(1)"}}, env)
    check("ordinary modelling is never blocked", code == 0)


def test_spend_guard():
    print("\nspend guard")
    import tempfile
    runs = tempfile.mkdtemp()
    env = {"BLENDPIPE_RUNS": runs, "BLENDPIPE_MAX_GENERATIONS": "2"}
    gen = {"session_id": "s1", "tool_name": "mcp__blender__generate_mesh",
           "tool_input": {"prompt": "a goblin"}}

    codes = [hook("guard_spend.py", gen, env)[0] for _ in range(3)]
    check("the first two paid generations pass", codes[:2] == [0, 0])
    code, err = hook("guard_spend.py", gen, env)
    check("the ceiling blocks further spend", code == 2)
    check("and points back at procedural", "execute_python" in err)
    check("and says how to raise it", "BLENDPIPE_MAX_GENERATIONS" in err)

    free = dict(env, BLENDPIPE_LOCAL_URL="http://127.0.0.1:8000")
    codes = [hook("guard_spend.py", {**gen, "session_id": "s2"}, free)[0] for _ in range(5)]
    check("local generation is free and uncapped", codes == [0] * 5)

    explicit = [hook("guard_spend.py",
                     {**gen, "session_id": "s3", "tool_input": {"prompt": "x", "backend": "local"}},
                     env)[0] for _ in range(5)]
    check("an explicit local backend is not counted", explicit == [0] * 5)

    code, _ = hook("guard_spend.py",
                   {"session_id": "s4", "tool_name": "Bash", "tool_input": {"command": "ls"}}, env)
    check("unrelated tools are ignored", code == 0)

if __name__ == "__main__":
    for fn in (test_bridge_roundtrip, test_bridge_errors, test_gates, test_uv_quality, test_backend_resolution,
               test_probe_is_valid_python, test_mcp_surface, test_mcp_survives_no_blender,
               test_addon_is_importable_shape,
               test_headless_agent, test_hooks_match_the_names_claude_code_sends,
               test_export_guard, test_spend_guard):
        fn()
    print("\n%d passed, %d failed" % (len(PASSED), len(FAILED)))
    if FAILED:
        print("failed: " + ", ".join(FAILED))
    sys.exit(1 if FAILED else 0)
